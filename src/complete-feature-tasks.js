const overlap=(a,b)=>a.x<b.x+b.w&&b.x<a.x+a.w&&a.z<b.z+b.d&&b.z<a.z+a.d;
const faceTouch=(a,b)=>((a.x+a.w===b.x||b.x+b.w===a.x)&&a.z<b.z+b.d&&b.z<a.z+a.d)||((a.z+a.d===b.z||b.z+b.d===a.z)&&a.x<b.x+b.w&&b.x<a.x+a.w);
// A work area may include a side-by-side table layout. That relationship is
// never used as evidence that the parts can be lifted as one assembly.
export function foundationAreas(bricks){
 const pending=new Set(bricks),groups=[];
 while(pending.size){
  const group=new Set([pending.values().next().value]);
  for(const b of group){pending.delete(b);for(const c of pending)if((b.y===c.y&&faceTouch(b,c))||(Math.abs(b.y-c.y)===1&&overlap(b,c)))group.add(c);}
  groups.push([...group]);
 }
 return groups;
}
const sorted=a=>[...a].sort(),same=(a,b)=>JSON.stringify(a)===JSON.stringify(b);
const count=r=>createBookletPresentation(r).numbering.diagramCount;

function foundation(bricks){
 const bottom=bricks.filter(b=>b.y===0),areas=new Map();
 for(const b of bottom)areas.set(b.color,(areas.get(b.color)??0)+b.w*b.d);
 const [color,area]=[...areas].sort((a,b)=>b[1]-a[1])[0]??[];
 if(!color||area<bottom.reduce((n,b)=>n+b.w*b.d,0)*.8)return null;
 const top=Math.max(...bricks.filter(b=>b.color===color).map(b=>b.y));
 return top<=2?{color,top}:null;
}

function sequenceModules(replay,bricks,by){
 const owners=new Map(replay.flatMap((m,i)=>m.brickIds.map(id=>[id,i]))),requires=replay.map(()=>new Set());
 for(const a of bricks)for(const b of bricks)if(a.y<b.y&&overlap(a,b)&&owners.get(a.id)!==owners.get(b.id))requires[owners.get(b.id)].add(owners.get(a.id));
 const directParents=replay.map(()=>new Set());
 for(const a of bricks)for(const b of bricks)if(a.y+1===b.y&&overlap(a,b)&&owners.get(a.id)!==owners.get(b.id))directParents[owners.get(b.id)].add(owners.get(a.id));
 const colors=replay.map(m=>new Set(m.brickIds.map(id=>by.get(id).color)));
 const affinity=(a,b)=>{
  if(!b)return 0;
  const ai=replay.indexOf(a),bi=replay.indexOf(b);
  const sameMaterial=[...colors[ai]].some(c=>colors[bi].has(c));
  const siblings=sameMaterial&&[...directParents[ai]].some(i=>directParents[bi].has(i)&&replay[i].brickIds.every(id=>by.get(id).y>0));
  return (siblings?10000:0)+a.brickIds.reduce((n,id)=>n+b.brickIds.filter(prior=>overlap(by.get(id),by.get(prior))&&by.get(id).color===by.get(prior).color).length,0);
 };
 const pending=new Set(replay.map((_,i)=>i)),ordered=[];
 while(pending.size){
  const ready=[...pending].filter(i=>![...requires[i]].some(j=>pending.has(j))).sort((i,j)=>affinity(replay[j],ordered.at(-1))-affinity(replay[i],ordered.at(-1))||Math.min(...replay[i].brickIds.map(id=>by.get(id).y))-Math.min(...replay[j].brickIds.map(id=>by.get(id).y)));
  if(!ready.length)throw Error('Task dependency cycle');
  const i=ready[0];pending.delete(i);ordered.push(replay[i]);
 }
 return ordered;
}

function groupTaskDiagrams(result,changedModules){
 const p=result.assemblyPlan,by=new Map(p.bricks.map(b=>[b.id,b])),steps=[];
 const make=ops=>{const first=ops[0],last=ops.at(-1),ids=ops.flatMap(s=>s.newBrickIds);return {...first,id:`panel-${first.id}`,newBrickIds:ids,highlightBrickIds:ops.length===1?first.highlightBrickIds:[...ids],visibleBrickIds:last.visibleBrickIds,
  issues:[...new Map(ops.flatMap(s=>s.issues).map(i=>[JSON.stringify(i),i])).values()],sourceStepIds:ops.map(s=>s.id),orderedOperations:ops.map(s=>({id:s.id,kind:s.kind,newBrickIds:s.newBrickIds,highlightBrickIds:s.highlightBrickIds,issues:s.issues,insertionDirection:s.insertionDirection??'down'}))};};
 // Only regroup newly planned tasks. Existing handled recipes keep the
 // presentation generated by their validated recipe and original metadata.
 const existingByFirstSource=new Map(result.instructionPlan.steps.filter(s=>!changedModules.has(s.moduleId)).map(s=>[s.sourceStepIds[0],s]));
 for(let i=0;i<p.steps.length;){const first=p.steps[i];
  if(!changedModules.has(first.moduleId)){const old=existingByFirstSource.get(first.id);if(!old)throw Error('Missing protected diagram');steps.push(old);i+=old.sourceStepIds.length;continue;}
  let end=i+1;if(first.kind==='build'&&first.placementGroupId)while(end<p.steps.length&&p.steps[end].placementGroupId===first.placementGroupId&&p.steps[end].kind==='build')end++;
  const ops=p.steps.slice(i,end),combined=make(ops),view=chooseInstructionView({visibleBricks:combined.visibleBrickIds.map(id=>by.get(id)),highlightedIds:combined.highlightBrickIds});
  steps.push(...(view.passes&&!view.truncated||ops.length===1?[combined]:ops.map(s=>make([s]))));i=end;
 }
 for(let i=0;i<steps.length-1;){const a=steps[i],b=steps[i+1],ids=[...a.newBrickIds,...b.newBrickIds],bs=ids.map(id=>by.get(id));
  if(!changedModules.has(a.moduleId)||a.kind!=='build'||b.kind!=='build'||a.moduleId!==b.moduleId||ids.length>12||Math.max(...bs.map(b=>b.y))-Math.min(...bs.map(b=>b.y))>2){i++;continue;}
  const view=chooseInstructionView({visibleBricks:b.visibleBrickIds.map(id=>by.get(id)),highlightedIds:ids});if(!view.passes||view.truncated){i++;continue;}
  steps.splice(i,2,{...a,newBrickIds:ids,highlightBrickIds:[...ids],visibleBrickIds:b.visibleBrickIds,issues:[...a.issues,...b.issues],sourceStepIds:[...a.sourceStepIds,...b.sourceStepIds],orderedOperations:[...a.orderedOperations,...b.orderedOperations]});
 }
 const instructionPlan={...result.instructionPlan,steps,stats:{...result.instructionPlan.stats,stepCount:steps.length,maxBricksPerStep:Math.max(...steps.map(s=>s.newBrickIds.length)),planReferenceCount:steps.reduce((n,s)=>n+s.newBrickIds.length+s.highlightBrickIds.length+s.visibleBrickIds.length,0)}};
 return {...result,instructionPlan,guide:createGuideSections(instructionPlan)};
}

function verify(before,after,held){
 const p=after.assemblyPlan,q=after.instructionPlan,source=new Map(p.steps.map(s=>[s.id,s]));
 if(!same(before.brickModel,after.brickModel)||!same(before.assemblyPlan.bricks,p.bricks))throw Error('Geometry changed');
 if(!same(sorted(q.steps.flatMap(s=>s.newBrickIds)),sorted(p.bricks.map(b=>b.id)))||!same(q.steps.flatMap(s=>s.sourceStepIds),p.steps.map(s=>s.id)))throw Error('Incomplete coverage');
 const op=s=>[s.id,s.kind,s.newBrickIds,s.highlightBrickIds,s.issues,s.insertionDirection??'down'];
 for(const s of q.steps)if(!same(sorted(s.newBrickIds),sorted(s.sourceStepIds.flatMap(id=>source.get(id).newBrickIds)))||!same(s.orderedOperations.map(op),s.sourceStepIds.map(id=>op(source.get(id)))))throw Error('Nonliteral operations');
 if(!same(sorted(unresolvedCells(p)),sorted(unresolvedCells(before.assemblyPlan))))throw Error('Physical failures changed');
 const issues=r=>sorted(r.steps.flatMap(s=>s.issues.map(i=>JSON.stringify(i))));
 if(!same(issues(p),issues(before.assemblyPlan))){
  const old=issues(before.assemblyPlan),current=issues(p),added=current.filter(x=>!old.includes(x)).map(JSON.parse),removed=old.filter(x=>!current.includes(x)).map(JSON.parse);
  const by=new Map(p.bricks.map(b=>[b.id,b]));
  const safelySupported=issue=>['temporary-hold','limited-support'].includes(issue.code)&&issue.brickIds?.length&&issue.brickIds.every(id=>{
   const step=p.steps.find(s=>s.newBrickIds.includes(id)),brick=by.get(id),module=p.modules.find(m=>m.id===step?.moduleId);
   return step?.kind==='build'&&module?.kind==='grounded'&&(step.insertionDirection??'down')==='down'&&!step.issues.some(i=>i.severity==='error')&&(brick.y===0||step.visibleBrickIds.some(prior=>!step.newBrickIds.includes(prior)&&by.get(prior).y===brick.y-1&&overlap(by.get(prior),brick)));
  });
  if(added.length||removed.some(i=>!safelySupported(i))){const error=Error('Warnings or failure diagnostics changed');error.detail={added,removed};throw error;}
 }
 for(const m of held){
  const old=before.assemblyPlan.steps.filter(s=>s.moduleId===m.id&&s.kind==='join'),now=p.steps.filter(s=>s.moduleId===m.id&&s.kind==='join');
  if(old.length!==now.length||old.some((s,i)=>!same(contactCells(before.assemblyPlan,s),contactCells(p,now[i]))))throw Error('Protected attachment contacts changed');
 }
 const repeat=r=>createBookletPresentation(r).presentation.sections.filter(s=>s.repeatCount>1).map(s=>[s.repeatCount,s.stepIds.length,sorted(s.instances.flatMap(i=>i.brickIds))]);
 if(!same(repeat(before),repeat(after)))throw Error('Repeated recipes changed');
 const oldBad=new Set([...chooseInstructionSequence(before.instructionPlan)].filter(([,v])=>!v.passes||v.truncated).map(([id])=>id));
 for(const [id,v]of chooseInstructionSequence(q))if((!v.passes||v.truncated||v.groups.some(g=>!g.visibleBrickCount))&&!oldBad.has(id))throw Error('An addition is hidden');
 if(count(after)>=count(before))throw Error('No diagram reduction');
}

function proposeCompleteFeatureTasks(before){
 const p=before.assemblyPlan;
 if(!p||before.assemblyError||p.bricks.length>1000)return {selected:false,reason:'Outside scope'};
 const by=new Map(p.bricks.map(b=>[b.id,b])),book=createBookletPresentation(before);
 const repeated=new Set(book.presentation.sections.filter(s=>s.repeatCount>1).flatMap(s=>s.instances.flatMap(i=>i.brickIds)));
 const failedModules=new Set(p.steps.filter(s=>s.issues.some(i=>i.severity==='error')).map(s=>s.moduleId));
 const held=recipeReplay(p,{preservePlacements:true}).filter(m=>m.buildContext||failedModules.has(m.id)||m.brickIds.some(id=>repeated.has(id)));
 const heldIds=new Set(held.flatMap(m=>m.brickIds)),ordinary=p.bricks.filter(b=>!heldIds.has(b.id)),base=foundation(ordinary)??(foundationAreas(ordinary.filter(b=>b.y===0)).length>1?{top:0,kind:'separate-grounded-components'}:null);
 if(!base)return {selected:false,reason:'No low dominant foundation',ordinaryParts:ordinary.length};
 try{
  const ground=ordinary.filter(b=>b.y<=base.top),upper=ordinary.filter(b=>b.y>base.top),areas=foundationAreas(ground),discovered=discoverComponentTasks(areas.length===1?upper:ordinary,{completeWorkAreas:true});
  if(!discovered||!upper.length)throw Error('No complete upper task partition');
  const tasks=areas.length===1?[ground,...discovered.tasks]:discovered.tasks,replay=tasks.map((bs,i)=>{const groups=createRectangularLayerGroups(bs,{maxBricks:24,maxSpan:32,maxPartTypes:8,balancePanels:true}).map(g=>g.brickIds);return {id:`task-area-${i}`,label:'Assembly',kind:'grounded',...(bs.some(b=>b.y===0)?{}:{groupType:'supported-additions'}),brickIds:bs.map(b=>b.id),brickOrder:groups.flat(),placementGroups:groups,actionOrder:true};});
  const failedHeld=held.filter(m=>failedModules.has(m.id)),failedIds=new Set(failedHeld.flatMap(m=>m.brickIds));
  const ordered=[...sequenceModules([...replay,...held.filter(m=>!failedModules.has(m.id))],p.bricks.filter(b=>!failedIds.has(b.id)),by),...failedHeld];
  const assemblyPlan=createAssemblyPlan({brickModel:before.brickModel,moduleReplay:ordered,moduleRecipes:replayNestedRecipes(p),integratedBuild:p.integratedBuild??false,allowUnderAttachments:true,allowWorkSurfaceUnderAttachments:true,preferLocalProgress:true,preferLocalFoundations:true});
  const compacted=compactAssemblyPlan(assemblyPlan);
  const prepared={...before,assemblyPlan,instructionPlan:compacted.plan,guide:createGuideSections(compacted.plan),assemblyEvaluation:{...before.assemblyEvaluation,compaction:compacted.report}};
  const retained=retainUnchangedDiagrams(before,restoreUnchangedRecipeMetadata(before,prepared));
  const after=prepareNestedRecipePresentation(groupTaskDiagrams(retained,new Set(replay.map(m=>m.id))));
  verify(before,after,held);
  return {selected:true,base,foundationAreas:areas.length,before:count(before),after:count(after),taskSizes:tasks.map(t=>t.length),result:after};
 }catch(error){return {selected:false,base,reason:error.message,...(error.detail?{detail:error.detail}:{})};}
}

// Only a verified complete task plan replaces the current guide. Established
// handled/repeated recipes and failed construction remain protected boundaries.
export function completeFeatureTasks(before){
 const proposal=proposeCompleteFeatureTasks(before);
 if(!proposal.selected)return before;
 const {result,...report}=proposal,p=result.assemblyPlan,q=result.instructionPlan;
 return {...result,completeFeatureTasks:report,assemblyEvaluation:{...result.assemblyEvaluation,
  after:assessAssemblyQuality(p),compaction:{...result.assemblyEvaluation?.compaction,
   sourceStepCount:p.steps.length,instructionDiagramCount:q.steps.length,
   collapsedStepCount:p.steps.length-q.steps.length,
   mergedDiagramCount:q.steps.filter(s=>s.sourceStepIds.length>1).length}}};
}
