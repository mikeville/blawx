// Rung-2 pilot: generate FLUX.1 schnell silhouette candidates for the
// icon-miss backlog (see scripts/seed-library.ts's misses.json / AGENTS.md
// "text-to-2D rung"), downsample each with the same 16×16 front-mask path
// as the icon pipeline (scripts/lib/silhouette.ts), and write eyeball
// artifacts for Fable-tier review. Provider is auto-selected at runtime from
// whichever API key is present — no model calls happen until a key is set
// and --dry-run is absent.
//
// Usage: npx tsx scripts/gen-silhouettes.ts [flags]
//   --out=<runId>       output run id (default gen1-16char-flux)
//   --nouns=<list>      comma-separated filter (hyphenated for multi-word,
//                       e.g. palm-tree); default is all 16 nouns below
//   --candidates=N      candidates per noun, seeds 1..N (default 4)
//   --dry-run           print provider, prompts, image count, cost estimate;
//                       exit 0 WITHOUT calling anything (works with no key)
//   --yes               required if planned image count > 80 (safety cap)
//   --skip-existing     candidates whose raw/<stem>.png already exists are
//                       re-downsampled from disk instead of regenerated
//                       (resume a partial run without paying twice)
//   --date=<YYYY-MM-DD> manifest date (default 2026-07-05)
//   Reads:  TOGETHER_API_KEY or REPLICATE_API_TOKEN (env or project .env)
//   Writes: runs/<runId>/raw/<noun-stem>-c<i>.png      generated bytes
//           runs/<runId>/masks/<noun-stem>-c<i>.txt    16×16 front mask
//           runs/<runId>/previews/<noun-stem>-c<i>.png mask upscaled to 512²
//           runs/<runId>/gen.json                      manifest

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { Resvg } from '@resvg/resvg-js';
import { decodePng, isInkDark, pixelsToFrontMask } from './lib/silhouette.ts';
import { maskToRows } from '../src/bench/maskOps.ts';

const SIZE = 16;
const PREVIEW_PX = 512;
const CELL_PX = PREVIEW_PX / SIZE; // 32
const CONCURRENCY = 4;
const YES_THRESHOLD = 80;

// --- CLI flags (process.argv.slice(2)) — see the usage comment above. ---
function parseFlag(name: string): string | undefined {
  const prefix = `--${name}=`;
  const arg = process.argv.slice(2).find((a) => a.startsWith(prefix));
  return arg?.slice(prefix.length);
}
const hasFlag = (name: string) => process.argv.slice(2).includes(`--${name}`);

const OUT_RUN_ID = parseFlag('out') ?? 'gen1-16char-flux';
const NOUNS_FILTER = parseFlag('nouns')?.split(',').map((s) => s.trim());
const CANDIDATES = Number(parseFlag('candidates') ?? '4');
const DRY_RUN = hasFlag('dry-run');
const YES = hasFlag('yes');
const SKIP_EXISTING = hasFlag('skip-existing');
const MANIFEST_DATE = parseFlag('date') ?? '2026-07-05';

// --- Minimal .env loader: project-root .env, simple KEY=VALUE lines, no
// dotenv dep. Only sets vars not already present in process.env. ---
function loadDotEnv(): void {
  const envPath = join(import.meta.dirname, '..', '.env');
  if (!existsSync(envPath)) return;
  const text = readFileSync(envPath, 'utf8');
  for (const rawLine of text.split('\n')) {
    const line = rawLine.trim();
    if (!line || line.startsWith('#')) continue;
    const eq = line.indexOf('=');
    if (eq === -1) continue;
    const key = line.slice(0, eq).trim();
    let value = line.slice(eq + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    if (!(key in process.env)) process.env[key] = value;
  }
}
loadDotEnv();

// noun -> {subject, view} for the base prompt template. Names with spaces
// use the noun itself for prompt text but hyphens for filenames (see
// nounFileStem). 12 icon-miss nouns (seed3-16char-fa misses.json) + 4
// weak-icon retries (hat/tree/ice-cream-cone/rocket-ship: the FA glyph
// doesn't survive 16×16 downsampling as a legible silhouette — tiered
